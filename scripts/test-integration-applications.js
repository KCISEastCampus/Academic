// Run after `bundle exec jekyll build`: numerical maths and rendered lesson links.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const close = (actual, expected) => assert(Math.abs(actual - expected) < 1e-6, `${actual} != ${expected}`);
const { sin, cos, tan, log, abs, PI } = Math;

// Check each indefinite answer by differentiation, away from singularities.
const answers = [
  [x => -cos(2*x)/2 + cos(2*x)**3/6, x => sin(2*x)**3],
  [x => x/2 + sin(6*x)/12, x => cos(3*x)**2],
  [x => 3*x/8 + sin(4*x)/8 + sin(8*x)/64, x => cos(2*x)**4],
  [x => tan(x)**2/2 + log(abs(cos(x))), x => tan(x)**3],
  [x => sin(x) - sin(x)**3/3, x => cos(x)**3],
  [x => sin(x)**3/3 - sin(x)**5/5, x => sin(x)**2*cos(x)**3],
  [x => tan(2*x)/2 - x, x => tan(2*x)**2],
];
for (const [F, f] of answers) {
  for (const x of [-0.4, 0.2, 0.6]) {
    const h = 1e-5;
    close((F(x+h) - F(x-h))/(2*h), f(x));
  }
}

// Compare exact answers with numerical integration of the original functions.
function integral(f, a, b) {
  const n = 12000;
  const h = (b-a)/n;
  let sum = f(a) + f(b);
  for (let i = 1; i < n; i++) sum += (i%2 ? 4 : 2)*f(a+i*h);
  return sum*h/3;
}
close(integral(x => abs(x*x-1), -2, 2), 4);
close(integral(x => x*x-1, -2, 2), 4/3);
close(integral(x => 2*x-x*x, 0, 2), 4/3);
close(PI*integral(x => (x+1)**2, 0, 2), 26*PI/3);
close(PI*integral(y => y-2, 2, 6), 8*PI);
close(integral(x => sin(2*x)**2, 0, PI/4), PI/8);
close(integral(x => 3*x-x*x, 0, 3), 9/2);
close(integral(x => x*x-4, -3, 3), -6);
close(integral(x => abs(x*x-4), -3, 3), 46/3);
close(PI*integral(x => cos(2*x)**2, 0, PI/4), PI*PI/8);
close(PI*integral(y => y-1, 1, 4), 9*PI/2);

const lessons = ['index', 'functions', 'modulus-and-transformations', 'algebraic-fractions-and-division', 'partial-fractions', 'integration', 'integration-applications', 'differential-equations', 'numerical-methods', 'vectors', 'binomial-series', 'trigonometric-functions-and-formulae', 'exponential-and-logarithmic-functions', 'differentiation', 'parametric-equations', 'mathematical-proof', 'quick-reference'];
for (const lesson of lessons) {
  const file = path.join(root, '_site/alevel/a2-mathematics', lesson === 'index' ? '' : lesson, 'index.html');
  const html = fs.readFileSync(file, 'utf8');
  for (const [, href] of html.matchAll(/href="([^"]+)"/g)) {
    if (!href.startsWith('/alevel/a2-mathematics/') && !href.startsWith('#')) continue;
    const [url, anchor] = href.split('#');
    const target = url ? path.join(root, '_site', url, 'index.html') : file;
    assert(fs.existsSync(target), `Missing linked page: ${href}`);
    if (anchor) {
      const destination = fs.readFileSync(target, 'utf8');
      // TOC links are generated by JavaScript; the layout contains their target IDs.
      assert(destination.includes(`id="${decodeURIComponent(anchor)}"`), `Missing anchor: ${href}`);
    }
  }
}
const source = fs.readFileSync(path.join(root, 'alevel/a2-mathematics/integration-applications.md'), 'utf8');
assert(!/[\u3400-\u9fff]/u.test(source), 'Lesson must use English.');
const rendered = fs.readFileSync(path.join(root, '_site/alevel/a2-mathematics/integration-applications/index.html'), 'utf8');
assert.equal((rendered.match(/<details\b/g) || []).length, 14);
assert(!rendered.includes('<p>$$'), 'Display maths must render as MathJax input.');
